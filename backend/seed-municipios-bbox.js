async function main() {
  console.log(`Updating ${municipios.length} municipalities with bounding boxes...`);

  let updated = 0;
  for (const [codigo, nome, uf, minLat, maxLat, minLng, maxLng] of municipios) {
    await pool.query(
      `INSERT INTO municipios (codigo, nome, uf, uf_sigla, min_lat, max_lat, min_lng, max_lng)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
       ON CONFLICT (codigo) DO UPDATE SET
         nome = EXCLUDED.nome, uf = EXCLUDED.uf, uf_sigla = EXCLUDED.uf_sigla,
         min_lat = EXCLUDED.min_lat, max_lat = EXCLUDED.max_lat,
         min_lng = EXCLUDED.min_lng, max_lng = EXCLUDED.max_lng`,
      [codigo, nome, uf, uf, minLat, maxLat, minLng, maxLng]
    );
    updated++;
  }

  console.log(`Updated ${updated} municipalities`);

  // Verify
  const { rows } = await pool.query(
    'SELECT COUNT(*) as total, COUNT(CASE WHEN min_lat != 0 THEN 1 END) as with_bbox FROM municipios'
  );
  console.log(`Database: ${rows[0].total} total, ${rows[0].with_bbox} with valid bbox`);

  await pool.end();
  process.exit(0);
}

main().catch(err => {
  console.error('Erro:', err);
  process.exit(1);
});
